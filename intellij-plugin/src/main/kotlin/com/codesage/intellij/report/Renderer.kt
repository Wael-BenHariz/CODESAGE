package com.codesage.intellij.report

import com.codesage.intellij.model.Finding
import com.codesage.intellij.model.GitCollection
import com.codesage.intellij.model.LocalReviewResult
import com.codesage.intellij.model.Severity
import com.codesage.intellij.model.UnifiedSeverity
import com.codesage.intellij.util.Html
import java.text.Collator
import java.util.Locale

data class DiagnosticViewState(
    val shown: Set<String>,
    val reasons: Map<String, String>,
)

sealed interface ReportViewState {
    data class Loading(val message: String) : ReportViewState
    data object Cancelled : ReportViewState
    data class Error(val message: String) : ReportViewState
    data class Result(
        val result: LocalReviewResult,
        val collection: GitCollection?,
        val diagnostics: DiagnosticViewState?,
    ) : ReportViewState
}

/**
 * Port of `vscode-extension/src/render.ts`.
 *
 * The HTML is compared byte-for-byte against goldens generated by the real VS
 * Code renderer (`src/test/resources/parity/expected`). Do not "improve"
 * markup, ordering or wording here without regenerating those goldens.
 */
object Renderer {
    private val REASON_LABELS = mapOf(
        "file_not_in_snapshot" to "file is not part of this snapshot",
        "file_deleted" to "file was deleted",
        "unsafe_path" to "path is outside the repository",
        "stale_snapshot" to "file changed after the snapshot",
        "file_unreadable" to "file could not be read",
        "line_missing" to "finding has no line number",
        "line_outside_diff" to "line is outside the reviewed diff",
    )

    private val INLINE_MARKDOWN =
        Regex("(`[^`]+`|\\*\\*[^*]+\\*\\*|\\*[^*\\s][^*]*\\*)")
    private val HEADING = Regex("^(#{1,6})\\s+(.*)$")
    private val BULLET = Regex("^[-*+]\\s+(.*)$")
    private val NUMBERED = Regex("^\\d+[.)]\\s+(.*)$")

    fun escapeHtml(value: String): String = Html.escape(value)

    fun commandUri(command: String, vararg args: String): String = Html.commandUri(command, *args)

    fun renderReportHtml(state: ReportViewState): String {
        val view = buildView(state)
        return buildString {
            append("<!DOCTYPE html>\n")
            append("<html lang=\"en\">\n")
            append("<head>\n")
            append("  <meta charset=\"UTF-8\">\n")
            append("  <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">\n")
            append("  <meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline';\">\n")
            append("  <style>\n")
            append(ReportCss.CSS)
            append("\n  </style>\n")
            append("  <title>CodeSage Code Review</title>\n")
            append("</head>\n")
            append("<body>\n")
            append("  <main>\n")
            append("    <header>\n")
            append("      <h1>CodeSage Code Review</h1>\n")
            append("      <p class=\"subtitle\">AI review from the local backend.</p>\n")
            append("      <span class=\"status ").append(view.statusClass).append("\">")
                .append(Html.escape(view.status)).append("</span>\n")
            append("    </header>\n")
            append("\n")
            append("    <section>\n")
            append("      <h2>Analysis</h2>\n")
            append("      <div class=\"summary md\">").append(view.analysis).append("</div>\n")
            append("    </section>\n")
            append("\n")
            append("    <section>\n")
            append("      <h2>Issues</h2>\n")
            append("      ").append(view.issues).append("\n")
            append("    </section>\n")
            append("\n")
            append("    ").append(view.excluded).append("\n")
            append("  </main>\n")
            append("</body>\n")
            append("</html>")
        }
    }

    fun renderMarkdown(markdown: String): String {
        val lines = markdown.replace("\r\n", "\n").split("\n")
        val html = mutableListOf<String>()
        val paragraph = mutableListOf<String>()
        var list: String? = null

        fun closeList() {
            if (list != null) {
                html.add("</$list>")
                list = null
            }
        }

        fun flushParagraph() {
            if (paragraph.isNotEmpty()) {
                html.add("<p>${inlineMarkdown(Html.escape(paragraph.joinToString(" ")))}</p>")
                paragraph.clear()
            }
        }

        for (raw in lines) {
            val line = raw.trim()
            if (line.isEmpty()) {
                flushParagraph()
                closeList()
                continue
            }

            val heading = HEADING.matchEntire(line)
            if (heading != null) {
                flushParagraph()
                closeList()
                val level = minOf(heading.groupValues[1].length + 2, 5)
                html.add("<h$level>${inlineMarkdown(Html.escape(heading.groupValues[2]))}</h$level>")
                continue
            }

            val bullet = BULLET.matchEntire(line)
            if (bullet != null) {
                flushParagraph()
                if (list != "ul") {
                    closeList()
                    html.add("<ul>")
                    list = "ul"
                }
                html.add("<li>${inlineMarkdown(Html.escape(bullet.groupValues[1]))}</li>")
                continue
            }

            val numbered = NUMBERED.matchEntire(line)
            if (numbered != null) {
                flushParagraph()
                if (list != "ol") {
                    closeList()
                    html.add("<ol>")
                    list = "ol"
                }
                html.add("<li>${inlineMarkdown(Html.escape(numbered.groupValues[1]))}</li>")
                continue
            }

            closeList()
            paragraph.add(line)
        }

        flushParagraph()
        closeList()
        return html.joinToString("")
    }

    fun groupFindings(findings: List<Finding>): List<Pair<String, List<Finding>>> {
        val groups = LinkedHashMap<String, MutableList<Finding>>()
        for (finding in findings.sortedWith { left, right -> Severity.compareFindings(left, right) }) {
            val key = finding.filePath.ifEmpty { "General" }
            groups.getOrPut(key) { mutableListOf() }.add(finding)
        }
        val collator = Collator.getInstance(Locale.ENGLISH)
        return groups.entries
            .sortedWith { left, right -> collator.compare(left.key, right.key) }
            .map { it.key to it.value }
    }

    private fun inlineMarkdown(escaped: String): String = INLINE_MARKDOWN.replace(escaped) { match ->
        val text = match.value
        when {
            text.startsWith("`") -> "<code>${text.substring(1, text.length - 1)}</code>"
            text.startsWith("**") -> "<strong>${text.substring(2, text.length - 2)}</strong>"
            else -> "<em>${text.substring(1, text.length - 1)}</em>"
        }
    }

    private fun severityClass(severity: UnifiedSeverity): String = when (severity) {
        UnifiedSeverity.CRITICAL, UnifiedSeverity.HIGH -> "sev-high"
        UnifiedSeverity.MEDIUM -> "sev-medium"
        UnifiedSeverity.LOW -> "sev-low"
        else -> "sev-info"
    }

    private fun renderFinding(finding: Finding, diagnostics: DiagnosticViewState?): String {
        val openHref = Html.commandUri("codesage.openFinding", finding.id)
        val location = if (finding.lineStart == null) {
            finding.filePath
        } else {
            "${finding.filePath}:${finding.lineStart}"
        }
        val note = if (diagnostics != null && !diagnostics.shown.contains(finding.id)) {
            diagnostics.reasons[finding.id]
        } else {
            null
        }

        val parts = mutableListOf<String>()
        parts.add("<li class=\"finding\">")
        parts.add("<a class=\"finding-title\" href=\"${Html.escape(openHref)}\" title=\"Open finding\">")
        parts.add("<span class=\"sev ${severityClass(finding.severity)}\">${Html.escape(finding.severity.wire)}</span>")
        parts.add("<span class=\"loc\">${Html.escape(location)}</span>")
        parts.add("<span class=\"msg\">${Html.escape(finding.message)}</span>")
        parts.add("</a>")

        if (finding.body.isNotEmpty() && finding.body != finding.message) {
            parts.add("<p class=\"body\">${Html.escape(finding.body)}</p>")
        }
        if (!finding.suggestion.isNullOrEmpty()) {
            val copyHref = Html.commandUri("codesage.copySuggestion", finding.id)
            parts.add(
                "<p class=\"suggestion\"><span>Suggestion:</span> ${Html.escape(finding.suggestion)} " +
                    "<a href=\"${Html.escape(copyHref)}\" title=\"Copy suggestion\">Copy</a></p>",
            )
        }
        val source = listOfNotNull(finding.tool, finding.ruleId)
            .filter { it.isNotEmpty() }
            .joinToString(" / ")
        if (source.isNotEmpty()) {
            val also = if (finding.alsoDetectedBy.isNotEmpty()) {
                " · also detected by ${finding.alsoDetectedBy.joinToString(", ")}"
            } else {
                ""
            }
            parts.add("<p class=\"source\">Source: ${Html.escape(source)}${Html.escape(also)}</p>")
        }
        if (note != null) {
            parts.add("<p class=\"note\">Not shown inline: ${Html.escape(REASON_LABELS[note] ?: note)}</p>")
        }
        if (!finding.snippet.isNullOrEmpty()) {
            parts.add("<pre class=\"snippet\">${Html.escape(finding.snippet)}</pre>")
        }
        parts.add("</li>")
        return parts.joinToString("")
    }

    private fun renderIssues(
        findings: List<Finding>,
        diagnostics: DiagnosticViewState?,
        emptyText: String,
    ): String {
        if (findings.isEmpty()) {
            return "<div class=\"issues\"><ul><li>${Html.escape(emptyText)}</li></ul></div>"
        }
        val groups = groupFindings(findings).joinToString("") { (filePath, group) ->
            val items = group.joinToString("") { renderFinding(it, diagnostics) }
            "<div class=\"file-group\">" +
                "<div class=\"file-head\"><span class=\"file-path\">${Html.escape(filePath)}</span>" +
                "<span class=\"file-count\">${group.size}</span></div>" +
                "<ul>$items</ul></div>"
        }
        return "<div class=\"issues\">$groups</div>"
    }

    private fun renderExcluded(excluded: List<com.codesage.intellij.model.ExcludedFile>): String {
        if (excluded.isEmpty()) {
            return ""
        }
        val items = excluded.joinToString("") {
            "<li><code>${Html.escape(it.path)}</code> — ${Html.escape(it.reason)}</li>"
        }
        return "<section><h2>Excluded files</h2><div class=\"excluded\"><ul>$items</ul></div></section>"
    }

    private class PanelView(
        val status: String,
        val statusClass: String,
        val analysis: String,
        val issues: String,
        val excluded: String,
    )

    // ------------------------------------------------------------------
    // Swing fallback (JCEF unavailable)
    //
    // The tool window panel uses the byte-identical HTML above whenever the
    // embedded browser (Chromium) is available. When it is not, the panel still
    // has to show the report *inside the IDE*, so these methods build a
    // simplified HTML 3.2 document that Swing's renderer understands (no CSS
    // layout, no scripts, no external resources).
    // ------------------------------------------------------------------

    /** Placeholder shown before the first review. */
    fun renderIdleHtml(): String = buildString {
        append("<html><body style='font-family: sans-serif; margin: 12px'>")
        append("<h2>CodeSage Code Review</h2>")
        append("<p>Run <b>CodeSage: Review Local Changes</b> to review the working tree, ")
        append("or <b>CodeSage: Review Staged Changes</b> for the staged index.</p>")
        append("<p>Findings also appear as editor annotations; this panel always lists every finding.</p>")
        append("</body></html>")
    }

    /** Simplified report for `JEditorPane` when JCEF is disabled or unavailable. */
    fun renderFallbackHtml(state: ReportViewState): String {
        val view = buildView(state)
        val result = (state as? ReportViewState.Result)?.result
        return buildString {
            append("<html><body style='font-family: sans-serif; margin: 12px'>")
            append("<h2>CodeSage Code Review</h2>")
            append("<p><b>").append(Html.escape(view.status)).append("</b></p>")
            append("<h3>Analysis</h3>")
            append(view.analysis)
            append("<h3>Issues</h3>")
            val findings = result?.findings ?: emptyList()
            if (findings.isEmpty()) {
                val empty = if (state is ReportViewState.Loading) {
                    "Waiting for the review to finish…"
                } else {
                    "No specific issues returned."
                }
                append("<p>").append(Html.escape(empty)).append("</p>")
            } else {
                append(renderFallbackFindings(findings, (state as ReportViewState.Result).diagnostics))
            }
            val excluded = (state as? ReportViewState.Result)?.collection?.excluded ?: emptyList()
            if (excluded.isNotEmpty()) {
                append("<h3>Excluded files</h3><ul>")
                for (file in excluded) {
                    append("<li><tt>").append(Html.escape(file.path)).append("</tt> — ")
                        .append(Html.escape(file.reason)).append("</li>")
                }
                append("</ul>")
            }
            append("</body></html>")
        }
    }

    private fun renderFallbackFindings(
        findings: List<Finding>,
        diagnostics: DiagnosticViewState?,
    ): String = buildString {
        for ((filePath, group) in groupFindings(findings)) {
            append("<h4>").append(Html.escape(filePath)).append("</h4><ul>")
            for (finding in group) {
                val location = if (finding.lineStart == null) {
                    finding.filePath
                } else {
                    "${finding.filePath}:${finding.lineStart}"
                }
                val openHref = Html.escape(Html.commandUri("codesage.openFinding", finding.id))
                append("<li><font color=\"").append(severityColor(finding.severity)).append("\"><b>")
                    .append(Html.escape(finding.severity.wire.uppercase(Locale.ROOT)))
                    .append("</b></font> <b><a href=\"").append(openHref).append("\">")
                    .append(Html.escape(location)).append("</a></b><br>")
                    .append(Html.escape(finding.message))
                if (finding.body.isNotEmpty() && finding.body != finding.message) {
                    append("<br><i>").append(Html.escape(finding.body)).append("</i>")
                }
                if (!finding.suggestion.isNullOrEmpty()) {
                    val copyHref = Html.escape(Html.commandUri("codesage.copySuggestion", finding.id))
                    append("<br>Suggestion: ").append(Html.escape(finding.suggestion))
                    append(" <a href=\"").append(copyHref).append("\">Copy</a>")
                }
                val source = listOfNotNull(finding.tool, finding.ruleId)
                    .filter { it.isNotEmpty() }
                    .joinToString(" / ")
                if (source.isNotEmpty()) {
                    append("<br>Source: ").append(Html.escape(source))
                    if (finding.alsoDetectedBy.isNotEmpty()) {
                        append(" · also detected by ")
                            .append(Html.escape(finding.alsoDetectedBy.joinToString(", ")))
                    }
                }
                val note = if (diagnostics != null && !diagnostics.shown.contains(finding.id)) {
                    diagnostics.reasons[finding.id]
                } else {
                    null
                }
                if (note != null) {
                    append("<br><i>Not shown inline: ")
                        .append(Html.escape(REASON_LABELS[note] ?: note)).append("</i>")
                }
                append("</li>")
            }
            append("</ul>")
        }
    }

    private fun severityColor(severity: UnifiedSeverity): String = when (severity) {
        UnifiedSeverity.CRITICAL, UnifiedSeverity.HIGH -> "#c0392b"
        UnifiedSeverity.MEDIUM -> "#b9770e"
        UnifiedSeverity.LOW -> "#1e8449"
        else -> "#5d6d7e"
    }

    private fun buildView(state: ReportViewState): PanelView = when (state) {
        is ReportViewState.Loading -> PanelView(
            status = "Reviewing…",
            statusClass = "",
            analysis = renderMarkdown(state.message),
            issues = renderIssues(emptyList(), null, "Waiting for the review to finish…"),
            excluded = "",
        )

        ReportViewState.Cancelled -> PanelView(
            status = "Review cancelled",
            statusClass = "status-muted",
            analysis = renderMarkdown("The review was cancelled before it completed."),
            issues = renderIssues(emptyList(), null, "No specific issues returned."),
            excluded = "",
        )

        is ReportViewState.Error -> PanelView(
            status = "Review failed",
            statusClass = "status-error",
            analysis = renderMarkdown(state.message),
            issues = renderIssues(emptyList(), null, "No specific issues returned."),
            excluded = "",
        )

        is ReportViewState.Result -> {
            val count = state.result.findings.size
            val files = state.result.statistics.filesReviewed
            PanelView(
                status = "$count finding${if (count == 1) "" else "s"} · " +
                    "$files file${if (files == 1) "" else "s"}",
                statusClass = "",
                analysis = renderMarkdown(state.result.summary.ifEmpty { "No summary returned." }),
                issues = renderIssues(
                    state.result.findings,
                    state.diagnostics,
                    "No specific issues returned.",
                ),
                excluded = renderExcluded(state.collection?.excluded ?: emptyList()),
            )
        }
    }
}
